/**
 * @file Утилиты для форматирования текста и строк.
 * @description Содержит функции для склонения слов по правилам русского языка,
 *              используемые в интерфейсе для корректного отображения количественных меток
 *              (например, «1 запись», «3 записи», «5 записей»).
 */

/**
 * Склоняет слово «запись» по числительному согласно правилам русского языка.
 *
 * @param {number} n - Число для склонения.
 * @returns {string} Правильная форма слова («запись», «записи» или «записей»).
 */
export function pluralizeRecords(n) {
  const m10 = n % 10;
  const m100 = n % 100;

  if (m10 === 1 && m100 !== 11) return "запись";
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return "записи";
  return "записей";
}